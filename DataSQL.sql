-- FreshVend TV2: Product / Inventory / Batch / Restock / Machine / Slot
-- PostgreSQL 15+ | Synthetic demo seed data | Coordinate Machine/Slot IDs with TV4.
BEGIN;

CREATE TABLE IF NOT EXISTS product_category (
  category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  description TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS product (
  product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES product_category(category_id),
  sku VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  description TEXT,
  price NUMERIC(12,2) NOT NULL CHECK (price > 0),
  unit VARCHAR(30) NOT NULL,
  low_stock_threshold INTEGER NOT NULL DEFAULT 5 CHECK (low_stock_threshold >= 0),
  status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','DISCONTINUED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS machine_location (
  location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  address TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS vending_machine (
  machine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id BIGINT NOT NULL REFERENCES machine_location(location_id),
  machine_code VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE','OFFLINE','MAINTENANCE','OUT_OF_ORDER')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS machine_slot (
  slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  machine_id BIGINT NOT NULL REFERENCES vending_machine(machine_id),
  slot_code VARCHAR(30) NOT NULL,
  product_id BIGINT REFERENCES product(product_id),
  capacity INTEGER NOT NULL DEFAULT 20 CHECK (capacity > 0),
  status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE','INACTIVE','MAINTENANCE','FAULT')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_machine_slot_code UNIQUE (machine_id, slot_code),
  CONSTRAINT uq_slot_product_pair UNIQUE (slot_id, product_id)
);

CREATE TABLE IF NOT EXISTS inventory_batch (
  batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES product(product_id),
  batch_code VARCHAR(60) NOT NULL,
  received_date DATE NOT NULL,
  expiry_date DATE NOT NULL,
  initial_quantity INTEGER NOT NULL CHECK (initial_quantity > 0),
  status VARCHAR(24) NOT NULL DEFAULT 'AVAILABLE'
    CHECK (status IN ('PENDING','AVAILABLE','EXPIRED','DEPLETED','QUARANTINED','DISPOSED','REJECTED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_batch_expiry_after_received CHECK (expiry_date >= received_date),
  CONSTRAINT uq_product_batch_code UNIQUE (product_id, batch_code),
  CONSTRAINT uq_batch_product_pair UNIQUE (batch_id, product_id)
);

CREATE TABLE IF NOT EXISTS inventory_stock (
  stock_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  slot_id BIGINT NOT NULL,
  quantity_on_hand INTEGER NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
  version BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_stock_batch_slot UNIQUE (batch_id, slot_id),
  CONSTRAINT fk_stock_batch_product FOREIGN KEY (batch_id, product_id)
    REFERENCES inventory_batch(batch_id, product_id),
  CONSTRAINT fk_stock_slot_product FOREIGN KEY (slot_id, product_id)
    REFERENCES machine_slot(slot_id, product_id)
);

CREATE TABLE IF NOT EXISTS restock (
  restock_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restock_code VARCHAR(60) NOT NULL UNIQUE,
  batch_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  slot_id BIGINT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actor_id VARCHAR(100) NOT NULL,
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_restock_batch_product FOREIGN KEY (batch_id, product_id)
    REFERENCES inventory_batch(batch_id, product_id),
  CONSTRAINT fk_restock_slot_product FOREIGN KEY (slot_id, product_id)
    REFERENCES machine_slot(slot_id, product_id)
);

CREATE TABLE IF NOT EXISTS inventory_movement (
  movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL,
  batch_id BIGINT NOT NULL,
  slot_id BIGINT NOT NULL,
  movement_type VARCHAR(24) NOT NULL
    CHECK (movement_type IN ('RESTOCK','ISSUE','ADJUSTMENT','DISPOSAL','TRANSFER_IN','TRANSFER_OUT')),
  quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
  reference_type VARCHAR(40),
  reference_id VARCHAR(100),
  actor_id VARCHAR(100) NOT NULL,
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_movement_batch_product FOREIGN KEY (batch_id, product_id)
    REFERENCES inventory_batch(batch_id, product_id),
  CONSTRAINT fk_movement_slot_product FOREIGN KEY (slot_id, product_id)
    REFERENCES machine_slot(slot_id, product_id)
);

CREATE TABLE IF NOT EXISTS inventory_alert (
  alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_type VARCHAR(24) NOT NULL CHECK (alert_type IN ('LOW_STOCK','NEAR_EXPIRY','EXPIRED_BATCH')),
  severity VARCHAR(16) NOT NULL DEFAULT 'MEDIUM' CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
  product_id BIGINT REFERENCES product(product_id),
  batch_id BIGINT REFERENCES inventory_batch(batch_id),
  slot_id BIGINT REFERENCES machine_slot(slot_id),
  message TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ACKNOWLEDGED','RESOLVED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  acknowledged_at TIMESTAMPTZ,
  resolved_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS audit_log (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id VARCHAR(100) NOT NULL,
  action VARCHAR(60) NOT NULL,
  entity_type VARCHAR(60) NOT NULL,
  entity_id VARCHAR(100) NOT NULL,
  old_value JSONB,
  new_value JSONB,
  reason TEXT,
  result VARCHAR(20) NOT NULL DEFAULT 'SUCCESS' CHECK (result IN ('SUCCESS','FAILURE')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS failed_job (
  job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_name VARCHAR(120) NOT NULL,
  job_key VARCHAR(180) NOT NULL UNIQUE,
  payload JSONB NOT NULL DEFAULT '{}'::JSONB,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  max_attempts INTEGER NOT NULL DEFAULT 5 CHECK (max_attempts > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING','RETRYING','SUCCEEDED','DEAD_LETTER')),
  next_retry_at TIMESTAMPTZ,
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_product_category_status ON product(category_id, status);
CREATE INDEX IF NOT EXISTS idx_product_name ON product USING GIN (to_tsvector('simple', name));
CREATE INDEX IF NOT EXISTS idx_machine_location ON vending_machine(location_id, status);
CREATE INDEX IF NOT EXISTS idx_slot_machine_status ON machine_slot(machine_id, status);
CREATE INDEX IF NOT EXISTS idx_batch_fifo ON inventory_batch(product_id, received_date, expiry_date, batch_id) WHERE status='AVAILABLE';
CREATE INDEX IF NOT EXISTS idx_batch_expiry ON inventory_batch(expiry_date, status);
CREATE INDEX IF NOT EXISTS idx_stock_product_slot ON inventory_stock(product_id, slot_id);
CREATE INDEX IF NOT EXISTS idx_restock_received ON restock(received_at DESC);
CREATE INDEX IF NOT EXISTS idx_movement_product_time ON inventory_movement(product_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_movement_batch ON inventory_movement(batch_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_alert_status_type ON inventory_alert(status, alert_type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_entity_time ON audit_log(entity_type, entity_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_actor_time ON audit_log(actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_failed_job_retry ON failed_job(status, next_retry_at)
  WHERE status IN ('PENDING','RETRYING');

